#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.md: the license of every module linked into the
# server and the Windows app, the Go standard library and runtime, and the
# libraries the web client ships. Run after changing a dependency; CI fails
# when the committed file is stale.
#
#   bash tools/notices.sh > THIRD_PARTY_NOTICES.md
set -euo pipefail
cd "$(dirname "$0")/../engine"
MC=$(go env GOMODCACHE)
GOROOT=$(go env GOROOT)
lic() { # $1 = directory: its license files, verbatim
  local found=0
  for f in "$1"/LICENSE* "$1"/LICENCE* "$1"/COPYING* "$1"/NOTICE*; do
    [ -f "$f" ] || continue
    found=1
    printf '\n```\n'; tr -d '\r' < "$f"; printf '\n```\n'
  done
  [ $found = 1 ] || { echo "no license file in $1" >&2; exit 1; }
}
echo "# Third-party notices"
echo
echo "Aether includes the software below. Each is listed with its license text,"
echo "as its license requires. Generated by \`tools/notices.sh\`."
echo
echo "## Go standard library and runtime ($(go env GOVERSION))"
lic "$GOROOT"
{
  GOOS=linux go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/aether
  GOOS=windows go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./cmd/aether-desktop
} | sort -u | while read -r path ver; do
  esc=$(printf '%s' "$path" | sed 's/[A-Z]/!\L&/g')
  echo
  echo "## $path $ver"
  lic "$MC/$esc@$ver"
done
for d in ../web/vendor/*/; do
  echo
  echo "## $(basename "$d") (web client, web/vendor/$(basename "$d"))"
  lic "$d"
done
